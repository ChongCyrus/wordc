import { launch, newContext, BASE, waitSeededHome, setupAi, injectPlanForWord, clickHomeLearn, enterAnnotation, boardWord, openAiPanel, shot, makeMockState, installMock, sleep } from './ai-qa-lib.mjs'
const browser = await launch()
const { context, page, bag } = await newContext(browser)
await installMock(page, makeMockState())
await page.goto(BASE, { waitUntil: 'domcontentloaded', timeout: 60000 })
await waitSeededHome(page)
await setupAi(page)
const injected = await injectPlanForWord(page, 1, { maxMeanings: true })
console.log('injected', injected)
await page.reload({ waitUntil: 'domcontentloaded' })
await waitSeededHome(page)
await clickHomeLearn(page)
await enterAnnotation(page)
console.log('word', await boardWord(page))
const gen = await openAiPanel(page)
await sleep(1200)
console.log('PANEL TEXT:\n', (await gen.innerText()).replace(/\n{2,}/g,'\n'))
console.log('pressed:', await gen.locator('button[aria-pressed="true"]').allInnerTexts())
console.log('selects:', await gen.locator('select').evaluateAll(els => els.map(e => ({ aria: e.getAttribute('aria-label'), value: e.value, options: [...e.options].map(o=>o.text) }))))
await shot(page, 'probe4-panel')
// modes
for (const mode of ['append','replace']) {
  const sel = gen.getByLabel('例句生成模式')
  await sel.selectOption(mode); await sleep(800)
  console.log(mode, '->', (await gen.innerText()).match(/目标：[^\n]*/)?.[0], '|', (await gen.innerText()).match(/预计 ¥[^\n]*/)?.[0])
}
// kinds
await gen.getByRole('button', { name: /^(✓ )?词组$/ }).click(); await sleep(700)
await gen.getByRole('button', { name: /^(✓ )?助记$/ }).click(); await sleep(700)
await gen.getByRole('button', { name: /^(✓ )?本义\/引申链$/ }).click(); await sleep(900)
console.log('all kinds ->', (await gen.innerText()).match(/目标：[^\n]*/)?.[0])
console.log('mode selects now', await gen.locator('select').evaluateAll(els=>els.map(e=>e.getAttribute('aria-label'))))
await shot(page, 'probe4-all-kinds')
// meanings
await gen.getByRole('button', { name: '指定含义', exact: true }).click(); await sleep(800)
console.log('MEANINGS TEXT:', (await gen.innerText()).match(/选择含义[\s\S]{0,500}/)?.[0])
console.log('start disabled', await gen.getByRole('button',{name:'开始生成',exact:true}).isDisabled())
console.log('draft count', (await import('./ai-qa-lib.mjs')).listDrafts ? await (await import('./ai-qa-lib.mjs')).listDrafts(page) : 'n/a')
await shot(page, 'probe4-meanings')
console.log('console errors', bag.consoleErrors, 'pageErrors', bag.pageErrors)
await context.close(); await browser.close()
